"""Builds src/data/tags/ladders.ts from the Codeforces API (problemset.problems).

For every tag: the most-solved problems in each rating band, so learners climb
from 800 upward on problems thousands of others have already solved.
Usage: python3 tools/build-ladders.py problems.json
"""
import json, sys, re

data = json.load(open(sys.argv[1]))
problems = data["result"]["problems"]
solved = {(s["contestId"], s["index"]): s["solvedCount"] for s in data["result"]["problemStatistics"]}
tags_ts = open("src/data/tags/tags.ts", encoding="utf-8").read()
TAGS = re.findall(r"t\('([a-z0-9-]+)', '([^']+)'", tags_ts)  # (slug, cf tag)

PER_BAND = {r: (2 if r <= 1600 else 1) for r in range(800, 2400, 100)}
out = {}
for slug, cf in TAGS:
    pool = [p for p in problems if cf in p["tags"] and p.get("rating") and "contestId" in p]
    pool.sort(key=lambda p: -solved.get((p["contestId"], p["index"]), 0))
    picked, seen = [], set()
    for band, k in PER_BAND.items():
        for p in [q for q in pool if q["rating"] == band][:k]:
            picked.append(p)
    if len(picked) < 10:  # rare tags: just the most-solved, any rating
        picked = pool[:15]
    picked.sort(key=lambda p: (p["rating"], -solved.get((p["contestId"], p["index"]), 0)))
    items = []
    for p in picked:
        key = (p["contestId"], p["index"])
        if key in seen:
            continue
        seen.add(key)
        items.append({"c": p["contestId"], "i": p["index"], "n": p["name"], "r": p["rating"], "s": solved.get(key, 0)})
    out[slug] = items

lines = [
    "// Generated by tools/build-ladders.py from the Codeforces API. Do not edit by hand.",
    "export type LadderItem = { c: number; i: string; n: string; r: number; s: number };",
    "",
    "export const LADDERS: Record<string, LadderItem[]> = " + json.dumps(out, ensure_ascii=False, indent=1) + ";",
    "",
]
open("src/data/tags/ladders.ts", "w", encoding="utf-8").write("\n".join(lines))
print({k: len(v) for k, v in out.items()})
print("total", sum(len(v) for v in out.values()))
